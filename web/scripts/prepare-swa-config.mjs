// prepare-swa-config.mjs — reads swa-config.template.json, substitutes runtime
// tenant info, and writes the resolved file to public/staticwebapp.config.json
// where Vite will copy it into the build output (dist/).
//
// ADR-0035 Phase D2 — also writes web/.env.production.local with the VITE_*
// env vars MSAL.js requires at build time. Vite picks these up automatically
// (https://vitejs.dev/guide/env-and-mode.html). The .local suffix means the
// file is gitignored — written fresh on every build from the surrounding
// process env populated by `azd env get-values`.
//
// Inputs (env):
//   AZURE_TENANT_ID — required. Falls back to 'organizations' for local /
//     CI builds that do not target a specific tenant.
//   AZURE_AEGIS_SPA_APP_ID — required for production. SPA app reg client ID
//     (from bootstrap-entra.ps1 Phase B `nativeAuth.spaAppId`). The
//     postprovision azd hook persists this via `azd env set`.
//   AZURE_AEGIS_API_APP_ID — required for production. API app reg client ID
//     (from bootstrap-entra.ps1 Phase B `nativeAuth.apiAppId`). v2.0 audience
//     (bare GUID) for outbound API tokens.
//
// Local dev workflow: developer creates web/.env.development.local manually
// with the relevant VITE_* keys; `vite dev` picks those up.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const templatePath = path.join(here, "..", "swa-config.template.json");
const outputPath = path.join(here, "..", "public", "staticwebapp.config.json");
const envOutputPath = path.join(here, "..", ".env.production.local");

const tenantId = process.env.AZURE_TENANT_ID ?? "organizations";
const spaClientId = process.env.AZURE_AEGIS_SPA_APP_ID ?? "";
const apiAppId = process.env.AZURE_AEGIS_API_APP_ID ?? "";

if (tenantId === "organizations") {
  console.warn(
    "[prepare-swa-config] AZURE_TENANT_ID not set — using 'organizations' placeholder. Production builds MUST set AZURE_TENANT_ID.",
  );
}
if (!spaClientId || !apiAppId) {
  console.warn(
    `[prepare-swa-config] AZURE_AEGIS_SPA_APP_ID / AZURE_AEGIS_API_APP_ID not fully set (spaClientId=${Boolean(spaClientId)} apiAppId=${Boolean(apiAppId)}) — production builds MUST set both for MSAL to function. Phase B bootstrap (bootstrap-entra.ps1) writes these to azd env via the postprovision hook.`,
  );
}

const template = await readFile(templatePath, "utf-8");
const resolved = template.replace(/TENANT_ID_PLACEHOLDER/g, tenantId);

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, resolved, "utf-8");
console.log(`[prepare-swa-config] wrote ${outputPath} (tenant=${tenantId})`);

// Vite-side env vars. Written even when SPA/API IDs are empty; the runtime
// in msalConfig.ts surfaces a clear error if a build attempts to ship without
// them (the build itself doesn't fail — that's a deploy-time signal).
const envBody = [
  `# AUTOGENERATED by prepare-swa-config.mjs — do not edit by hand.`,
  `# ADR-0035 Phase D2 — VITE_* env vars consumed by web/src/auth/msalConfig.ts.`,
  `VITE_AEGIS_TENANT_ID=${tenantId}`,
  `VITE_AEGIS_SPA_CLIENT_ID=${spaClientId}`,
  `VITE_AEGIS_API_AUDIENCE=${apiAppId}`,
  ``,
].join("\n");
await writeFile(envOutputPath, envBody, "utf-8");
console.log(
  `[prepare-swa-config] wrote ${envOutputPath} (VITE_AEGIS_TENANT_ID, VITE_AEGIS_SPA_CLIENT_ID, VITE_AEGIS_API_AUDIENCE)`,
);
