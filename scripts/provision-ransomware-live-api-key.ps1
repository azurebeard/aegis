<#
.SYNOPSIS
  Provision (first deploy) or rotate (operator-triggered) the
  ransomware.live PRO API key secret in Key Vault.

.DESCRIPTION
  ADR-0037. The API key is operator-supplied (obtained from
  https://www.ransomware.live/my) — unlike the recipient-hash pepper +
  report-share signing key, the value is NOT randomly generated by this
  script. The operator pastes their key into a secure prompt; the script
  validates it against `GET /validate` on the ransomware.live API before
  writing to Key Vault.

  Operating modes:
    * `-Mode Provision`  — write the secret only if it does not already
                           exist. Idempotent + safe to run on every deploy.
    * `-Mode Rotate`     — write a NEW secret VERSION regardless of
                           existing state. Operator-triggered (incident
                           response, departing operator with KV access,
                           ransomware.live forced rotation, etc.).

  Auth: relies on the caller's `az login` context. The caller MUST have
  `Key Vault Secrets Officer` on the target vault. The `infra/modules/
  keyvault.bicep` deployer-grant covers operator (user) and azd (SP) cases
  when `AZURE_DEPLOYER_OBJECT_ID` is set in the azd env. ADR-0037 +
  L12-FT-02 extend the multi-secret Officer allowlist to include this
  secret name.

  No Function App restart needed by default — the threatIntel ingest path
  reads the KV secret on each Timer fire (no module-scope cache). A
  manual restart via `-FunctionAppName` is supported anyway for parity
  with the other provisioning scripts + for the case where the operator
  wants to confirm the next ingest run immediately rather than waiting
  for the next hourly Timer fire.

.PARAMETER KeyVaultName
  The KV name (e.g. `kv-aegis-dev-uks`). Sourced from azd env
  `KEY_VAULT_NAME` (Bicep output) or `AZURE_KEY_VAULT_NAME` (legacy) if
  unspecified.

.PARAMETER SecretName
  The secret name. Defaults to `ransomware-live-api-key` (matches the
  `infra/modules/functions.bicep` app-setting default + the Bicep
  `ransomwareLiveSecretName` literal at `main.bicep:104`).

.PARAMETER Mode
  `Provision` (default — write only if absent) or `Rotate` (always write a
  new version).

.PARAMETER ApiKey
  Optional. When supplied, the script uses this value verbatim. When
  omitted, the script reads the value from an interactive `Read-Host
  -AsSecureString` prompt (canonical PowerShell pattern for secret
  capture; the value never appears in the process command line / shell
  history / scripted-exec logs).

.PARAMETER SkipValidate
  When supplied, the script does NOT call `GET /validate` against the
  ransomware.live API before writing the secret. Useful for offline
  rotations or if the ransomware.live service is temporarily down at
  rotation time. Operator accepts the risk that the key may be invalid
  until the next Timer fire surfaces a 401 in IngestHealth.

.PARAMETER FunctionAppName
  Optional. When supplied, the script restarts the Function App at the
  end so the next ingest run starts immediately rather than waiting for
  the next hourly Timer fire.

.PARAMETER ResourceGroupName
  Required when `-FunctionAppName` is supplied.

.EXAMPLE
  # First deploy after `azd provision` lands the new RBAC. Interactive
  # secure prompt for the key value.
  ./scripts/provision-ransomware-live-api-key.ps1 `
      -KeyVaultName kv-aegis-dev-uks

.EXAMPLE
  # Rotation, with immediate restart so the new key takes effect at the
  # next manual Ingest-now button press instead of the next hourly Timer.
  ./scripts/provision-ransomware-live-api-key.ps1 -Mode Rotate `
      -KeyVaultName kv-aegis-dev-uks `
      -FunctionAppName func-aegis-api-dev-2435ae1d `
      -ResourceGroupName rg-aegis-dev-uks

.NOTES
  This script writes to Key Vault. Use `-WhatIf` for a dry-run. Exit code
  0 on success; non-zero on failure (KV write failed, az CLI not
  authenticated, key failed validation, etc.).
#>

[CmdletBinding(SupportsShouldProcess)]
param(
    [string] $KeyVaultName,
    [string] $SecretName = 'ransomware-live-api-key',
    [ValidateSet('Provision', 'Rotate')]
    [string] $Mode = 'Provision',
    [string] $ApiKey,
    [switch] $SkipValidate,
    [string] $FunctionAppName,
    [string] $ResourceGroupName
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Write-Step {
    param([string] $Message)
    [Console]::Error.WriteLine("[provision-ransomware-live-api-key] $Message")
}

# ---- Parameter resolution ----
if ([string]::IsNullOrWhiteSpace($KeyVaultName)) {
    # azd persists the Bicep output as `KEY_VAULT_NAME` (no AZURE_ prefix).
    # Fall back to either name so manual operator invocations work whether
    # the env is sourced from `azd env get-values` or any custom export.
    $KeyVaultName = if (-not [string]::IsNullOrWhiteSpace($env:KEY_VAULT_NAME)) {
        $env:KEY_VAULT_NAME
    } else {
        $env:AZURE_KEY_VAULT_NAME
    }
}
if ([string]::IsNullOrWhiteSpace($KeyVaultName)) {
    throw "KeyVaultName is required. Pass -KeyVaultName or set KEY_VAULT_NAME (Bicep output) or AZURE_KEY_VAULT_NAME."
}
if ([string]::IsNullOrWhiteSpace($SecretName)) {
    throw "SecretName must be non-empty (default is 'ransomware-live-api-key')."
}

# Drift guard for manual invocations — mirrors L12-FT-FT-PS1-WARN pattern.
# When `-SecretName` was NOT explicitly passed (using the PS1 default) AND
# the azd env carries a Bicep-emitted canonical (`RANSOMWARE_LIVE_SECRET_NAME`)
# that differs, warn the operator to align. Silent in the happy path.
if (-not $PSBoundParameters.ContainsKey('SecretName') -and `
    -not [string]::IsNullOrWhiteSpace($env:RANSOMWARE_LIVE_SECRET_NAME) -and `
    $env:RANSOMWARE_LIVE_SECRET_NAME -ne $SecretName) {
    Write-Warning ("-SecretName not specified; using PS1 default '{0}'. " +
        "Bicep canonical from azd env is '{1}'. The two surfaces have drifted. " +
        "Re-run with -SecretName '{1}' to align with the deployed ABAC, or " +
        "update the PS1 default to match if the rename is intentional." -f $SecretName, $env:RANSOMWARE_LIVE_SECRET_NAME)
}
if (-not [string]::IsNullOrWhiteSpace($FunctionAppName) -and [string]::IsNullOrWhiteSpace($ResourceGroupName)) {
    throw "-FunctionAppName requires -ResourceGroupName so the restart can target the right resource."
}

# ---- az CLI sanity check ----
$azAccount = & az account show --output json 2>&1
if ($LASTEXITCODE -ne 0) {
    throw "az CLI is not authenticated. Run 'az login' first. Output: $azAccount"
}

Write-Step "Mode=$Mode  KV=$KeyVaultName  Secret=$SecretName"

# ---- Existence check ----
$secretShow = & az keyvault secret show --vault-name $KeyVaultName --name $SecretName --output json 2>&1
$secretExists = ($LASTEXITCODE -eq 0)
if ($secretExists) {
    Write-Step "Existing secret found. Latest version: $(($secretShow | ConvertFrom-Json).id)"
} else {
    # `az keyvault secret show` returns non-zero on 404 AND on any other
    # error (permissions, vault not found). Distinguish via the stderr text.
    if ($secretShow -match 'SecretNotFound|was not found') {
        Write-Step "Secret does not yet exist."
    } else {
        throw "az keyvault secret show failed unexpectedly. Output: $secretShow"
    }
}

# ---- Provision/Rotate decision ----
if ($Mode -eq 'Provision' -and $secretExists) {
    Write-Step "Mode=Provision and secret already exists — no-op. Use -Mode Rotate to force a new version."
    Write-Output @{
        keyVaultName = $KeyVaultName
        secretName = $SecretName
        mode = $Mode
        action = 'no_op_existing'
        validated = $false
        functionAppRestarted = $false
    } | ConvertTo-Json -Compress
    exit 0
}

# ---- Capture the API key value ----
# Unlike the pepper / signing-key scripts, the key value is operator-
# supplied (obtained from https://www.ransomware.live/my). When -ApiKey
# is omitted, prompt securely so the value never appears in process
# command line / shell history / scripted-exec logs.
$apiKeyValue = $null
if (-not [string]::IsNullOrWhiteSpace($ApiKey)) {
    $apiKeyValue = $ApiKey
} else {
    $securePrompt = Read-Host -Prompt "Paste your ransomware.live PRO API key (input hidden)" -AsSecureString
    if ($null -eq $securePrompt -or $securePrompt.Length -eq 0) {
        throw "No API key supplied. Generate one at https://www.ransomware.live/my and re-run."
    }
    # Convert the SecureString to a plain string just long enough to write
    # to KV (the value MUST travel as plain UTF-8 in the az CLI call
    # below). Best-effort scrub afterwards.
    $bstr = [System.Runtime.InteropServices.Marshal]::SecureStringToBSTR($securePrompt)
    try {
        $apiKeyValue = [System.Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
    } finally {
        [System.Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
    }
}
if ([string]::IsNullOrWhiteSpace($apiKeyValue)) {
    throw "API key is empty. Generate one at https://www.ransomware.live/my and re-run."
}

# ---- Pre-write validation against ransomware.live API ----
# Round-trips `GET /validate` with the supplied key. A 200 confirms the
# key is currently active; anything else fails the script BEFORE the KV
# write so the operator doesn't deploy a broken key. `-SkipValidate`
# bypasses for offline rotations.
if (-not $SkipValidate) {
    Write-Step "Validating key against https://api-pro.ransomware.live/validate ..."
    try {
        $validateResp = Invoke-RestMethod `
            -Method GET `
            -Uri 'https://api-pro.ransomware.live/validate' `
            -Headers @{ 'X-API-KEY' = $apiKeyValue } `
            -TimeoutSec 30 `
            -ErrorAction Stop
        # The API returns a small JSON object naming the client when the
        # key is valid. Don't pin the exact shape — log a redacted summary.
        Write-Step "Validation OK (response received; key recognised by API)."
    } catch {
        # Surface the HTTP status if the response carried one. Don't log
        # the response body — it may echo the supplied key in some error
        # branches.
        $statusCode = $_.Exception.Response.StatusCode.value__ 2>$null
        if ($null -ne $statusCode) {
            throw "Validation against ransomware.live FAILED (HTTP $statusCode). Key not written. Use -SkipValidate to bypass (offline rotation)."
        } else {
            throw "Validation against ransomware.live FAILED (network or unknown error). Key not written. Use -SkipValidate to bypass (offline rotation). Error: $($_.Exception.Message)"
        }
    }
} else {
    Write-Step "Skipping pre-write validation (-SkipValidate)."
}

if (-not $PSCmdlet.ShouldProcess("$KeyVaultName/$SecretName", "Set secret (mode=$Mode)")) {
    Write-Step "Dry-run (-WhatIf): would write a new secret version."
    $apiKeyValue = $null
    exit 0
}

# ---- Write to KV ----
# `az keyvault secret set` ALWAYS creates a new version, never edits
# existing versions in place. Provision and Rotate use the same call;
# difference is only the existence check above.
#
# IMPORTANT: pass the value via a temp file to avoid leaking it via the
# process command line (visible in `ps`, audit logs, etc.). az supports
# `--file` for this exact reason.
$tmp = [System.IO.Path]::GetTempFileName()
try {
    [System.IO.File]::WriteAllText($tmp, $apiKeyValue, [System.Text.Encoding]::UTF8)
    $setOutput = & az keyvault secret set --vault-name $KeyVaultName --name $SecretName --file $tmp --output json 2>&1
    if ($LASTEXITCODE -ne 0) {
        throw "az keyvault secret set failed: $setOutput"
    }
    $newSecret = $setOutput | ConvertFrom-Json
    Write-Step "Wrote new secret version: $($newSecret.id)"
} finally {
    Remove-Item $tmp -Force -ErrorAction SilentlyContinue
    # Best-effort scrub of the variable in memory (PowerShell GC is
    # non-deterministic; this is a tidy-up, not a security boundary).
    $apiKeyValue = $null
}

# ---- Optional Function App restart ----
# Unlike the pepper script, restart is OPTIONAL by design. The ingest lib
# reads KV on every Timer fire (no module-scope cache), so the next
# hourly fire picks up the new key automatically. Restart is offered for
# operators who want to confirm the new key immediately via the SPA's
# "Ingest now" admin button rather than waiting for the next Timer.
$restarted = $false
if (-not [string]::IsNullOrWhiteSpace($FunctionAppName)) {
    if ($PSCmdlet.ShouldProcess("$ResourceGroupName/$FunctionAppName", 'Restart Function App so the next ingest run starts immediately')) {
        Write-Step "Restarting Function App $FunctionAppName ..."
        $restartOutput = & az functionapp restart --name $FunctionAppName --resource-group $ResourceGroupName --output none 2>&1
        if ($LASTEXITCODE -ne 0) {
            throw "az functionapp restart failed: $restartOutput"
        }
        $restarted = $true
        Write-Step "Function App restarted. The next ingest run will use the new key."
    }
} else {
    Write-Step "No -FunctionAppName supplied. The new key takes effect at the next hourly Timer fire OR the next 'Ingest now' admin button press from the SPA."
}

Write-Output @{
    keyVaultName = $KeyVaultName
    secretName = $SecretName
    mode = $Mode
    action = if ($secretExists) { 'rotated_new_version' } else { 'provisioned_first' }
    validated = (-not $SkipValidate)
    functionAppRestarted = $restarted
} | ConvertTo-Json -Compress
